#!/usr/bin/env python3
"""Generate/check the disclosed command reference from the shipped CLI's help."""
import argparse
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
REFERENCE = ROOT / 'skills/automation-pilot-cli/references/command-reference.md'
COMMON = {'output', 'timeout', 'print-request', 'insecure', 'response-envelope', 'read-retries'}

def run(binary, *args):
    return subprocess.check_output([str(binary), *args], text=True, stderr=subprocess.STDOUT)

def render(binary):
    surface = json.loads(run(binary, 'surface'))
    lines = ['# autopi command reference', '',
        'Generated by `ci/cli/contracts/helpdocs.py` from the bundled CLI. Run',
        '`autopi <resource> <verb> --help` for usage, defaults, and examples.', '',
        'For wire types, limits, permissions, HTTP outcomes, and schema exceptions, read',
        '[API contracts](api-contract.md). For workflows, read [recipes](recipes.md).', '',
        '## Shared options', '',
        '| Option | Behavior |', '|---|---|',
        '| `--output json/raw` | Pretty JSON or verbatim body |',
        '| `--response-envelope` | JSON status, selected headers, and body; mutually exclusive with raw/status/ETag selectors |',
        '| `--print-request` | Redacted offline preview; no API calls |',
        '| `--timeout` | Total request deadline, default 30s |',
        '| `--read-retries N` | GET/HEAD 429/503 only, 0–5 retries within the same deadline |',
        '| `--insecure` | Explicit TLS-verification escape hatch |', '',
        'Bodies support `-f FILE`, `-f -`, `--data JSON`, `--data @file`, and `--data @-`.',
        'Bearer authentication is the only supported mode; connection credentials are environment-only.',
        'See the [CLI entrypoint](../SKILL.md) for setup and response protection.', '']
    contents = ['## Contents', '', '- [Shared options](#shared-options)']
    contents += ['- [' + resource['name'] + '](#' + resource['name'] + ')' for resource in surface]
    contents += ['- [Raw API and validation](#raw-api-and-validation)', '']
    index = lines.index('## Shared options')
    lines[index:index] = contents
    for resource in surface:
        name = resource['name']
        lines += ['## ' + name, '', '| Verb | Calls | Specific flags |', '|---|---|---|']
        for verb in resource['verbs']:
            help_text = run(binary, name, verb, '--help')
            calls = re.search(r'CALLS\n\s+([^\n]+)', help_text)
            flags = sorted(set(re.findall(r'^  -([a-z][a-z-]*)', help_text, re.M)) - COMMON)
            call_text = (calls.group(1) if calls else 'See help').replace('|', r'\|')
            lines.append('| `' + verb + '` | ' + call_text + ' | ' + ', '.join('`' + ('-' if len(flag) == 1 else '--') + flag + '`' for flag in flags) + ' |')
        lines.append('')
    lines += ['## Raw API and validation', '',
        '```text', 'autopi api METHOD PATH [-f FILE|- | --data JSON|@file|@-] [--header K:V] [--content-type TYPE]',
        'autopi lint [--kind KIND] [--mode authoring|api] [--read-back] [--output text|json] FILE...',
        'autopi policy', 'autopi surface', '```', '',
        'Raw API preserves the configured authentication and Input response protection,',
        'and bypasses the pinned request validator. Custom Authorization is rejected.',
        'Lint separates API request requirements from naming/sensitivity/expression policy.',
        'Exit 6 means lint findings; exit 7 means one or more bulk action items failed.', '']
    return '\n'.join(lines)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--binary', type=Path, default=ROOT / 'skills/automation-pilot-cli/scripts/autopi')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = render(args.binary.resolve())
    if args.check:
        if REFERENCE.read_text() != result:
            parser.exit(1, 'Command reference differs from CLI help; regenerate it.\n')
    else:
        REFERENCE.write_text(result)
    print('Command reference and complete help surface verified')

if __name__ == '__main__':
    main()
